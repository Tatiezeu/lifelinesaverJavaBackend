    EXECUTE IMMEDIATE 'ALTER TABLE USERS ADD (PROFILE_PICTURE CLOB)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN NULL; ELSE RAISE; END IF;
END;
/

-- 2. CLIENT_PROFILES table
BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE CLIENT_PROFILES (
        ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        USER_ID          NUMBER NOT NULL UNIQUE,
        PHONE            VARCHAR2(30 CHAR),
        INSURANCE_POLICY VARCHAR2(100 CHAR),
        VEHICLE_MAKE     VARCHAR2(80 CHAR),
        VEHICLE_MODEL    VARCHAR2(80 CHAR),
        VEHICLE_YEAR     VARCHAR2(10 CHAR),
        LICENSE_PLATE    VARCHAR2(20 CHAR),
        CONSTRAINT FK_CP_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

